const configs = new Map();

function diagram(kind, title, summary, nodes, relations, thread) {
  return { kind, title, summary, nodes, relations, thread };
}

function register(path, config) {
  configs.set(path, config);
}

function registerCategory(directory, kind, entries) {
  for (const [slug, config] of Object.entries(entries)) {
    register(`${directory}/${slug}.html`, diagram(kind, ...config));
  }
}

