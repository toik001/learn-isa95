function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function plainText(markup) {
  return markup
    .replace(/<[^>]+>/g, "")
    .replaceAll("&amp;", "&")
    .replaceAll("&quot;", '"')
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replace(/\s+/g, " ")
    .trim();
}

function renderDiagram(relativePath, html) {
  const config = configs.get(relativePath);
  if (!config) {
    throw new Error(`Missing learning diagram config for ${relativePath}`);
  }

  const pageTitle = plainText(html.match(/<h1>([\s\S]*?)<\/h1>/)?.[1] ?? "");
  if (!pageTitle) {
    throw new Error(`Missing h1 for ${relativePath}`);
  }

  const key = relativePath.replace(/\.html$/, "");
  const id = `diagram-${key.replaceAll("/", "-")}-title`;
  const nodes = config.nodes.map(([label, detail], index) => `
      <article class="learning-diagram__node" role="listitem">
        <span class="learning-diagram__index">${String(index + 1).padStart(2, "0")}</span>
        <strong>${escapeHtml(label)}</strong>
        <span>${escapeHtml(detail)}</span>
      </article>`);
  const flow = [];
  nodes.forEach((node, index) => {
    flow.push(node);
    if (index < config.relations.length) {
      flow.push(`
      <div class="learning-diagram__connector" aria-label="${escapeHtml(config.relations[index])}">
        <span>${escapeHtml(config.relations[index])}</span><b aria-hidden="true">→</b>
      </div>`);
    }
  });

  return `<!-- learning-diagram:start -->
  <figure class="learning-diagram" data-diagram-key="${escapeHtml(key)}" aria-labelledby="${id}" aria-label="${escapeHtml(pageTitle)} 学习图表">
    <figcaption id="${id}">
      <span class="learning-diagram__kind">${escapeHtml(config.kind)}</span>
      <strong>${escapeHtml(config.title)}</strong>
      <p class="learning-diagram__summary">${escapeHtml(config.summary)}</p>
    </figcaption>
    <div class="learning-diagram__flow" role="list">${flow.join("")}
    </div>
    <div class="learning-diagram__thread"><strong>关键线索</strong><span>${escapeHtml(config.thread)}</span></div>
  </figure>
  <!-- learning-diagram:end -->`;
}

export function upsertLearningDiagram(html, relativePath) {
  const withoutExisting = html.replace(
    /\s*<!-- learning-diagram:start -->[\s\S]*?<!-- learning-diagram:end -->/g,
    "",
  );
  const diagramMarkup = renderDiagram(relativePath, withoutExisting);

  if (relativePath === "index.html") {
    const updated = withoutExisting.replace(
      /(<main id="learning-map">)/,
      `$1\n    ${diagramMarkup}`,
    );
    if (updated === withoutExisting) {
      throw new Error("Could not locate index learning map insertion point");
    }
    return updated;
  }

  const updated = withoutExisting.replace(
    /(<div class="disclaimer">[\s\S]*?<\/div>)/,
    `$1\n  ${diagramMarkup}`,
  );
  if (updated === withoutExisting) {
    throw new Error(`Could not locate disclaimer insertion point for ${relativePath}`);
  }
  return updated;
}

